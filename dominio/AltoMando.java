package dominio;

public class AltoMando {
	private int numero;
	private String nombre;
	
	
	
	public AltoMando(int numero, String nombre) {
		super();
		this.numero = numero;
		this.nombre = nombre;
	}
	public int getNumero() {
		return numero;
	}
	public String getNombre() {
		return nombre;
	}
	
	
}
